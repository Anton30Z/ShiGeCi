export function getWordMeanings(word: VocabWord, language: LanguageCode): string[] {
  if (language === 'ru' && word.meaningsRu && word.meaningsRu.length > 0) {
    return word.meaningsRu;
  }
  return word.meanings;
}

export function getContextualExample(
  word: VocabWord,
  language: LanguageCode = 'en'
): ExampleSentence {
  if (word.example) return word.example;

  const firstMeaning = getWordMeanings(word, language)[0] || word.simplified;
  return {
    zh: `请用“${word.simplified}”造一个句子。`,
    pinyin: `Qǐng yòng "${word.pinyin}" zào yī gè jùzi.`,
    en: `Practice using "${word.simplified}" (${firstMeaning}) in a sentence.`,
    ru: `Составьте предложение со словом «${word.simplified}» (${firstMeaning}).`,
  };
}
