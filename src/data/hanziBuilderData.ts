export function buildStage3WordPuzzles(vocabWords: VocabWord[]): BuilderPuzzle[] {
  const pool = vocabWords.length > 0 ? vocabWords : STARTER_HSK1_WORDS;
  const multiChar = pool.filter((w) => {
    const chars = Array.from(w.simplified).filter((c) => /[\u4e00-\u9fff]/.test(c));
    return chars.length >= 2 && chars.length <= 3 && chars.join('') === w.simplified;
  });

  const source = multiChar.length >= 6 ? multiChar : STARTER_HSK1_WORDS.filter((w) => Array.from(w.simplified).length >= 2);

  return source.slice(0, 48).map((w) => ({
    id: `s3-${w.id}`,
    stage: 3,
    target: w.simplified,
    pinyin: w.pinyin,
    meaningRu: w.meaningsRu?.[0] ?? w.meanings[0] ?? w.simplified,
    meaningEn: w.meanings[0] ?? w.simplified,
    parts: Array.from(w.simplified),
    strictOrder: true,
  }));
}
